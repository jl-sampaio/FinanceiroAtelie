import java.sql.*;
import javax.swing.JOptionPane;

public class Database {

    // Banco H2 embutido: cria o arquivo financeiro_atelie.mv.db na pasta do projeto
    private static final String URL = "jdbc:h2:./financeiro_atelie;DB_CLOSE_DELAY=-1";

    static {
        try {
            Class.forName("org.h2.Driver");
        } catch (ClassNotFoundException e) {
            JOptionPane.showMessageDialog(null,
                "Driver H2 não encontrado!\nVerifique se o arquivo lib/h2.jar está presente.",
                "Erro fatal", JOptionPane.ERROR_MESSAGE);
            System.exit(1);
        }
    }

    public static Connection getConnection() throws SQLException {
        return DriverManager.getConnection(URL, "sa", "");
    }

    public static void inicializar() {
        String usuarios =
            "CREATE TABLE IF NOT EXISTS usuarios (" +
            "  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
            "  nome       VARCHAR(60)  NOT NULL UNIQUE," +
            "  salt       VARCHAR(64)  NOT NULL," +
            "  senha_hash VARCHAR(128) NOT NULL" +
            ")";

        String lancamentos =
            "CREATE TABLE IF NOT EXISTS lancamentos (" +
            "  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
            "  tipo      VARCHAR(10)   NOT NULL," +
            "  categoria VARCHAR(60)   NOT NULL," +
            "  descricao VARCHAR(200)  NOT NULL DEFAULT ''," +
            "  valor     DECIMAL(12,2) NOT NULL," +
            "  data_lanc DATE          NOT NULL," +
            "  usuario   VARCHAR(60)   NOT NULL," +
            "  criado_em TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL" +
            ")";

        try (Connection conn = getConnection();
             Statement st = conn.createStatement()) {
            st.execute(usuarios);
            st.execute(lancamentos);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,
                "Erro ao inicializar o banco de dados:\n" + e.getMessage(),
                "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }
}
